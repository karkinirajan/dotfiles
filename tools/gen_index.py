#!/usr/bin/env python3
"""Generate INDEX.md and chapter tables from Markdown frontmatter.

``gen_index.py`` writes the files, ``gen_index.py --check`` fails when they are
out of date (used in CI so the index cannot rot).
"""
from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

from _lib import LOG, markdown_files, repo_root, setup_logging, split_frontmatter

HEADER = "<!-- GENERATED by tools/gen_index.py from frontmatter. Do not edit by hand. -->\n"
PART_TITLES = {
    "01": "System",
    "02": "Desktop",
    "03": "Terminal",
    "04": "Editors",
    "05": "AI",
    "06": "Tools",
    "07": "Networking",
}


def collect(root: Path) -> list[tuple[Path, dict]]:
    items: list[tuple[Path, dict]] = []
    for md in markdown_files(root):
        rel = md.relative_to(root)
        if rel.parts[0] == "docs" or "references" in rel.parts or "reference" in rel.parts:
            continue
        try:
            meta, _ = split_frontmatter(md.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if meta.get("title") and meta.get("topic"):
            items.append((rel, meta))
    return sorted(items, key=lambda it: it[0].as_posix())


def row(rel: Path, meta: dict, base: Path) -> str:
    link = Path("/".join([".."] * len(base.parts)) if base.parts else ".") / rel
    shown = link.as_posix().removeprefix("./")
    return f"| [{meta['title']}]({shown}) | `{rel.as_posix()}` | {meta.get('last_verified', '')} | {meta.get('status', '')} |"


def build_index(root: Path, items: list[tuple[Path, dict]]) -> str:
    lines = [
        HEADER,
        "# Index",
        "",
        "Every chapter in reading order. Regenerate with `python3 tools/gen_index.py`.",
        "",
        "| Chapter | Path | Last verified | Status |",
        "|---|---|---|---|",
    ]
    lines += [row(rel, meta, Path()) for rel, meta in items]
    return "\n".join(lines) + "\n"


def build_setup_readme(root: Path, items: list[tuple[Path, dict]]) -> str | None:
    base = Path("01-system/cachyos/setup")
    mine = [(rel, meta) for rel, meta in items if rel.parent == base and rel.name != "README.md"]
    if not mine:
        return None
    lines = [
        HEADER,
        "# Setup guide: chapters",
        "",
        "The CachyOS developer workstation guide, one numbered chapter per file. It is the optional application and configuration catalog; the package manifests in `../packages/` are authoritative for baseline installs and `../../../fresh-setup.md` is the ordered procedure.",
        "",
        "Hardware profile: AMD Ryzen 5 5600, Radeon RX 6700 XT (gfx1031), 32 GiB RAM, Btrfs. Desktop: Hyprland with Noctalia. Profile: Python backend, AI/ML and full-stack development.",
        "",
        "| # | Chapter | Last verified | Status |",
        "|---|---|---|---|",
    ]
    for rel, meta in mine:
        lines.append(f"| {meta.get('chapter', '')} | [{meta['title']}]({rel.name}) | {meta.get('last_verified', '')} | {meta.get('status', '')} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args(argv)
    setup_logging(args.verbose)
    root = repo_root()
    items = collect(root)
    targets: dict[Path, str] = {root / "INDEX.md": build_index(root, items)}
    setup_readme = build_setup_readme(root, items)
    if setup_readme is not None:
        targets[root / "01-system/cachyos/setup/README.md"] = setup_readme
    stale = 0
    for path, content in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == content:
            continue
        stale += 1
        if args.check:
            LOG.error("STALE %s (run tools/gen_index.py)", path.relative_to(root))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            LOG.info("wrote %s", path.relative_to(root))
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    logging.getLogger().setLevel(logging.INFO)
    sys.exit(main())
